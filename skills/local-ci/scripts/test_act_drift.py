"""python3 test_act_drift.py — one self-check of the drift logic."""
import subprocess
import tempfile
from pathlib import Path

from act_drift import check

WF = """name: CI
on:
  push:
    branches: [dev]
  pull_request:
permissions:
  contents: read
concurrency:
  group: ci
jobs:
  win:
    strategy:
      matrix:
        os: [windows-latest]
    runs-on: ${{ matrix.os }}
    steps: [{run: echo}]
  build:
    runs-on: ubuntu-latest
    permissions:
      id-token: write
    steps:
      - run: echo ${{ secrets.NUGET_KEY }} ${{ secrets.GITHUB_TOKEN }} ${{ vars.CONFIG }}
  mac:
    runs-on: [macos-14]
    steps: [{run: echo}]
"""

with tempfile.TemporaryDirectory() as d:
    root = Path(d)
    subprocess.run(["git", "init", "-q", d], check=True)
    (root / ".github/workflows").mkdir(parents=True)
    (root / ".github/workflows/ci.yml").write_text(WF)

    r = check(root)
    w = r["workflows"][0]
    assert w["triggers"] == ["push", "pull_request"], w["triggers"]
    assert w["github_only"] == ["macos-14", "windows-latest"], w["github_only"]
    assert w["unmapped"] == ["ubuntu-latest"]
    assert w["missing_secrets"] == ["NUGET_KEY"]  # GITHUB_TOKEN is passed per run
    assert w["missing_vars"] == ["CONFIG"] and w["oidc"]
    assert any("gitignore" in x for x in r["drift"])

    (root / ".actrc").write_text("-P ubuntu-latest=catthehacker/ubuntu:act-latest\n")
    (root / ".secrets").write_text("NUGET_KEY=x\n")
    (root / ".vars").write_text("CONFIG=y\n")
    assert any("NOT gitignored" in x for x in check(root)["drift"])
    (root / ".gitignore").write_text(".secrets\n")
    assert check(root)["drift"] == [], check(root)["drift"]

    # empty value = known-absent secret, counts as covered
    (root / ".secrets").write_text("NUGET_KEY=\n")
    assert check(root)["drift"] == []

    # host-path flag in project .actrc is drift
    (root / ".actrc").write_text("-P ubuntu-latest=img\n--artifact-server-path /tmp/a\n")
    assert any("artifact-server-path" in x for x in check(root)["drift"])

    # generated header detected
    (root / ".github/workflows/ci.yml").write_text("# <auto-generated>\n# This code was generated.\n" + WF)
    assert check(root)["workflows"][0]["generated"]
print("ok")
